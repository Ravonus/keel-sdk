// Dependency-free Keel web3:// stream loader.
//
// Proves that ANY HTML viewer or page can consume Keel recursion through
// the standards surface with zero Keel code and zero libraries: plain
// JSON-RPC `eth_call` over fetch(), a hand-rolled ABI codec for the ERC-5219
// `request()` interface, ERC-7617 `web3-next-chunk` traversal, and
// ERC-7618-style decompression via the platform's DecompressionStream.
// Works in browsers and Node 18+ unchanged.
//
// The native Keel model behind this is exactly:
//   readChunk(objectId, index) -> (data, hasNext)   nextIndex = index + 1
// The linked-URL view followed here is generated by the adapter per response
// and stored nowhere on chain.

const REQUEST_SELECTOR = "1374c460"; // request(string[],(string,string)[])
const READ_CHUNK_SELECTOR = "c203cb0c"; // readChunk(bytes32,uint256)

// ---------------------------------------------------------------------------
// Minimal ABI primitives (32-byte words, big-endian).

function hexToBytes(hex) {
  const clean = hex.startsWith("0x") ? hex.slice(2) : hex;
  const out = new Uint8Array(clean.length / 2);
  for (let i = 0; i < out.length; i += 1) out[i] = parseInt(clean.slice(i * 2, i * 2 + 2), 16);
  return out;
}

function bytesToHex(bytes) {
  let out = "0x";
  for (const byte of bytes) out += byte.toString(16).padStart(2, "0");
  return out;
}

function word(value) {
  return value.toString(16).padStart(64, "0");
}

function readWord(bytes, offset) {
  let value = 0n;
  for (let i = 0; i < 32; i += 1) value = (value << 8n) | BigInt(bytes[offset + i]);
  return value;
}

function encodeString(text) {
  const utf8 = new TextEncoder().encode(text);
  const padded = Math.ceil(utf8.length / 32) * 32;
  let hex = word(utf8.length) + bytesToHex(utf8).slice(2).padEnd(padded * 2, "0");
  return hex;
}

// Encodes request(resource, []) calldata for a resource path of plain strings.
export function encodeRequestCalldata(resource) {
  const heads = [];
  const tails = [];
  let tailOffset = resource.length * 32;
  for (const segment of resource) {
    heads.push(word(tailOffset));
    const encoded = encodeString(segment);
    tails.push(encoded);
    tailOffset += encoded.length / 2;
  }
  const resourceArray = word(resource.length) + heads.join("") + tails.join("");
  // Outer heads: offset of resource array (0x40), offset of empty params array.
  const paramsOffset = 0x40 + resourceArray.length / 2;
  return "0x" + REQUEST_SELECTOR + word(0x40n) + word(BigInt(paramsOffset)) + resourceArray + word(0n);
}

// Decodes (uint16 statusCode, string body, (string,string)[] headers).
// The body is returned as raw bytes: chunk payloads are binary, not text.
export function decodeRequestReturn(returnHex) {
  const data = hexToBytes(returnHex);
  const statusCode = Number(readWord(data, 0));
  const bodyOffset = Number(readWord(data, 32));
  const bodyLength = Number(readWord(data, bodyOffset));
  const body = data.slice(bodyOffset + 32, bodyOffset + 32 + bodyLength);
  const headersOffset = Number(readWord(data, 64));
  const headerCount = Number(readWord(data, headersOffset));
  const headers = {};
  const decoder = new TextDecoder();
  const arrayData = headersOffset + 32;
  for (let i = 0; i < headerCount; i += 1) {
    const tupleOffset = arrayData + Number(readWord(data, arrayData + i * 32));
    const readField = (fieldIndex) => {
      const fieldOffset = tupleOffset + Number(readWord(data, tupleOffset + fieldIndex * 32));
      const length = Number(readWord(data, fieldOffset));
      return decoder.decode(data.slice(fieldOffset + 32, fieldOffset + 32 + length));
    };
    headers[readField(0).toLowerCase()] = readField(1);
  }
  return { statusCode, body, headers };
}

// Decodes (bytes data, bool hasNext) from readChunk.
export function decodeReadChunkReturn(returnHex) {
  const data = hexToBytes(returnHex);
  const bytesOffset = Number(readWord(data, 0));
  const length = Number(readWord(data, bytesOffset));
  return {
    data: data.slice(bytesOffset + 32, bytesOffset + 32 + length),
    hasNext: readWord(data, 32) === 1n,
  };
}

// ---------------------------------------------------------------------------
// Transport.

async function ethCall(rpcUrl, to, calldata) {
  const response = await fetch(rpcUrl, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "eth_call", params: [{ to, data: calldata }, "latest"] }),
  });
  const payload = await response.json();
  if (payload.error) throw new Error(`eth_call failed: ${payload.error.message}`);
  return payload.result;
}

function concatBytes(parts) {
  const total = parts.reduce((sum, part) => sum + part.length, 0);
  const out = new Uint8Array(total);
  let cursor = 0;
  for (const part of parts) {
    out.set(part, cursor);
    cursor += part.length;
  }
  return out;
}

async function decompress(bytes, encoding) {
  // Keel Deflate is zlib-wrapped, matching the viewer's convention.
  const format = { gzip: "gzip", deflate: "deflate", br: null }[encoding];
  if (encoding === "br") throw new Error("brotli decompression is not available in DecompressionStream");
  if (!format) throw new Error(`unsupported content-encoding: ${encoding}`);
  const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream(format));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

// ---------------------------------------------------------------------------
// Public surface.

/// Native indexed access: one chunk by (objectId, index), random access.
export async function fetchChunk({ rpcUrl, store, objectId, index }) {
  const calldata = "0x" + READ_CHUNK_SELECTOR + objectId.slice(2) + word(BigInt(index));
  return decodeReadChunkReturn(await ethCall(rpcUrl, store, calldata));
}

/// ERC-5219/7617 streaming access: starts at `/object/<objectId>`, follows
/// `web3-next-chunk` until absent, applies Content-Encoding when present and
/// decodable. `maxChunks` is the client-side traversal budget the ERCs leave
/// to the client (ERC-7617 specifies none).
export async function fetchStream({ rpcUrl, adapter, objectId, maxChunks = 4096 }) {
  let resource = ["object", objectId];
  const parts = [];
  let statusCode;
  let headers;
  for (let hops = 0; ; hops += 1) {
    if (hops >= maxChunks) throw new Error(`traversal budget exceeded (${maxChunks} chunks)`);
    const decoded = decodeRequestReturn(await ethCall(rpcUrl, adapter, encodeRequestCalldata(resource)));
    if (hops === 0) {
      statusCode = decoded.statusCode;
      headers = decoded.headers;
      if (statusCode !== 200) {
        return { statusCode, headers, body: decoded.body, contentType: headers["content-type"] ?? "" };
      }
    }
    parts.push(decoded.body);
    const next = decoded.headers["web3-next-chunk"];
    if (next === undefined) break;
    // The adapter emits same-contract absolute-path relatives: /object/<id>/<n>.
    if (!next.startsWith("/")) throw new Error(`unexpected next-chunk URL shape: ${next}`);
    resource = next.slice(1).split("/").map((segment) => decodeURIComponent(segment));
  }
  let body = concatBytes(parts);
  const contentEncoding = headers["content-encoding"];
  if (contentEncoding !== undefined) body = await decompress(body, contentEncoding);
  return { statusCode, headers, body, contentType: headers["content-type"] ?? "application/octet-stream" };
}
