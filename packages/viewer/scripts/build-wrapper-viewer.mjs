/**
 * Bundle the wrapper viewer into one importable module.
 *
 * The document that ships inside a token is a single file with no imports and
 * no requests, so the parts have to be flattened at build time. This produces
 * `dist/wrapper-viewer.js`: the stylesheet, the markup and the bundled app as
 * strings, plus the assembler already bound to them.
 *
 * Minified on purpose. These bytes are paid for once when the composite is
 * written and again on every single read of every token that uses it, so
 * whitespace here is a permanent tax on everyone who ever looks at the work.
 */
import { build } from "esbuild";
import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "src", "wrapper-viewer");
const dist = join(here, "..", "dist");

/** Strip what a browser does not need. Conservative: comments and the spaces
 *  around syntax, nothing that could change a selector's meaning. */
const minifyCss = (css) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s*([{}:;,>])\s*/g, "$1")
    .replace(/;\}/g, "}")
    .replace(/\s+/g, " ")
    .trim();

const minifyHtml = (html) =>
  html
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/>\s+</g, "><")
    .trim();

const bundled = await build({
  entryPoints: [join(src, "app.js")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2022",
  write: false,
  legalComments: "none",
});

const app = bundled.outputFiles[0].text.trim();
const css = minifyCss(await readFile(join(src, "viewer.css"), "utf8"));
const markup = minifyHtml(await readFile(join(src, "viewer.html"), "utf8"));

await mkdir(join(dist, "wrapper-viewer"), { recursive: true });
await copyFile(join(src, "document.js"), join(dist, "wrapper-viewer", "document.js"));

await writeFile(
  join(dist, "wrapper-viewer.js"),
  `// Generated by scripts/build-wrapper-viewer.mjs from src/wrapper-viewer/. Do not edit.\n` +
    `import { makeKeelWrapperViewerDocument } from "./wrapper-viewer/document.js";\n` +
    `export { makeKeelWrapperViewerDocument, keelWrapperViewerUri, encodeKeelPercentDataUri, encodeKeelBase64DataUri } from "./wrapper-viewer/document.js";\n` +
    `export const KEEL_WRAPPER_VIEWER_CSS = ${JSON.stringify(css)};\n` +
    `export const KEEL_WRAPPER_VIEWER_MARKUP = ${JSON.stringify(markup)};\n` +
    `export const KEEL_WRAPPER_VIEWER_APP = ${JSON.stringify(app)};\n` +
    `export const keelWrapperViewerDocument = makeKeelWrapperViewerDocument({\n` +
    `  css: KEEL_WRAPPER_VIEWER_CSS,\n  markup: KEEL_WRAPPER_VIEWER_MARKUP,\n  app: KEEL_WRAPPER_VIEWER_APP,\n});\n`,
);

await writeFile(
  join(dist, "wrapper-viewer.d.ts"),
  `// Generated by scripts/build-wrapper-viewer.mjs. Do not edit.\n` +
    `export interface KeelWrapperViewerOptions {\n` +
    `  /** The artwork, already base64. Carried by the document, never fetched. */\n` +
    `  readonly artworkBase64?: string;\n` +
    `  /** What the chain says about this token. Presentation only. */\n` +
    `  readonly context?: Readonly<Record<string, unknown>>;\n` +
    `  readonly title?: string;\n}\n` +
    `export declare const KEEL_WRAPPER_VIEWER_CSS: string;\n` +
    `export declare const KEEL_WRAPPER_VIEWER_MARKUP: string;\n` +
    `export declare const KEEL_WRAPPER_VIEWER_APP: string;\n` +
    `/** Percent-encode every UTF-8 payload byte outside RFC 3986 unreserved. */\n` +
    `export declare function keelWrapperViewerUri(document: string): string;\n` +
    `export declare function encodeKeelPercentDataUri(mediaType: string, value: string | Uint8Array): string;\n` +
    `export declare function encodeKeelBase64DataUri(mediaType: string, value: string | Uint8Array): string;\n` +
    `export declare function makeKeelWrapperViewerDocument(parts: {\n` +
    `  readonly css: string;\n  readonly markup: string;\n  readonly app: string;\n` +
    `}): (options?: KeelWrapperViewerOptions) => string;\n` +
    `export declare function keelWrapperViewerDocument(options?: KeelWrapperViewerOptions): string;\n`,
);

const total = css.length + markup.length + app.length;
console.log(
  `wrapper viewer: css ${css.length} B · markup ${markup.length} B · app ${app.length} B · chrome ${total} B`,
);
